import { useState } from 'react'
import { Code2, RefreshCw } from 'lucide-react'

const SOURCES = [
  { id: 'postgres', emoji: '🐘', label: 'PostgreSQL',  sub: 'Feed System' },
  { id: 'mongodb',  emoji: '🍃', label: 'MongoDB',     sub: 'Production System' },
  { id: 'csv',      emoji: '📄', label: 'CSV Files',   sub: 'Milk Buyers & Genetics' },
]

const TARGET_TABLES = [
  { id: 'dim_farm',            emoji: '🏠', label: 'dim_farm' },
  { id: 'dim_animal',          emoji: '🐄', label: 'dim_animal' },
  { id: 'dim_customer',        emoji: '👤', label: 'dim_customer' },
  { id: 'fact_milk_production', emoji: '🥛', label: 'fact_milk_production' },
  { id: 'fact_feed_event',     emoji: '🌾', label: 'fact_feed_event' },
  { id: 'full_pipeline',       emoji: '📦', label: 'Full Pipeline (all tables)' },
]

const INCLUDE_OPTIONS = [
  { id: 'validation', label: 'Validation checks',  defaultOn: true  },
  { id: 'logging',    label: 'Logging & monitoring', defaultOn: true  },
  { id: 'rollback',   label: 'Rollback capability',  defaultOn: false },
]

const ETL_SCRIPT = `# ============================================================
# ETL: dim_farm  |  Gold Layer  |  Farm One Data Platform
# Generated by AI · 2024-06-15
# ============================================================

from pyspark.sql import SparkSession
from pyspark.sql.functions import col, trim, upper, coalesce, lit, current_timestamp
import logging

spark = SparkSession.builder.appName("dim_farm_gold").getOrCreate()
logger = logging.getLogger("dim_farm_etl")

# === READ SOURCES ===
pg_farms = spark.read.format("jdbc") \\
    .option("url", "jdbc:postgresql://***:5432/feed_mgmt") \\
    .option("dbtable", "farms") \\
    .load()
# Loaded 5 farms from PostgreSQL (feed_management)

mongo_farms = spark.read.format("mongodb") \\
    .option("uri", "mongodb://***:27017/production_tracking") \\
    .option("collection", "farms") \\
    .load()
# Loaded 5 farms from MongoDB (production_tracking)

# === STANDARDISE ===
pg_std = pg_farms.select(
    col("farm_code").alias("source_id"),
    trim(col("farm_name")).alias("farm_name"),
    upper(col("country_code")).alias("country"),
    col("region"),
    lit("postgresql").alias("source_system")
)

mongo_std = mongo_farms.select(
    col("farm_id").cast("string").alias("source_id"),
    trim(col("name")).alias("farm_name"),
    upper(col("country")).alias("country"),
    col("region"),
    lit("mongodb").alias("source_system")
)

# === FUZZY MATCH & DEDUPLICATE ===
# AI: Name similarity threshold 85% — auto-merge; 60-85% — flag for review
combined = pg_std.union(mongo_std)
deduped = combined.dropDuplicates(["farm_name", "country"])
# Removed 0 exact duplicates; 2 fuzzy matches flagged for review

# === VALIDATION CHECKS ===
validated = deduped.filter(
    col("farm_name").isNotNull() &
    col("country").isNotNull() &
    (col("country").isin("GB", "IE", "NL", "NZ", "US"))
)
rejected = deduped.subtract(validated)
# Validation: 5 rows passed · 0 rejected

# === WRITE GOLD ===
validated.withColumn("etl_timestamp", current_timestamp()) \\
    .write.format("delta") \\
    .mode("overwrite") \\
    .option("path", "./data/delta/gold/dim_farm") \\
    .saveAsTable("gold.dim_farm")

logger.info(f"dim_farm complete: {'{validated.count()}'} rows written")`

export default function AdminEtl() {
  const [sources, setSources] = useState<Set<string>>(new Set(SOURCES.map(s => s.id)))
  const [target, setTarget] = useState('dim_farm')
  const [includes, setIncludes] = useState<Set<string>>(
    new Set(INCLUDE_OPTIONS.filter(o => o.defaultOn).map(o => o.id)),
  )

  function toggleSource(id: string) {
    setSources(prev => {
      const next = new Set(prev)
      next.has(id) ? next.delete(id) : next.add(id)
      return next
    })
  }

  function toggleInclude(id: string) {
    setIncludes(prev => {
      const next = new Set(prev)
      next.has(id) ? next.delete(id) : next.add(id)
      return next
    })
  }

  return (
    <div className="p-6 space-y-5 max-w-screen-xl mx-auto">
      {/* Page header */}
      <div>
        <h1 className="text-xl font-bold text-gray-900">ETL Generator</h1>
        <p className="text-sm text-gray-400 mt-0.5">
          AI generates transformation scripts with edge case handling
        </p>
      </div>

      {/* Time-saved banner */}
      <div className="rounded-xl bg-gradient-to-r from-amber-50 to-green-50 p-4 flex items-center gap-4">
        <div className="flex-1 bg-amber-100 text-amber-800 rounded-xl p-4">
          <p className="text-xs font-semibold text-amber-600 uppercase tracking-wide mb-0.5">Manual Effort</p>
          <p className="text-lg font-bold">4–8 weeks</p>
          <p className="text-xs text-amber-700">Writing, testing, and documenting ETL pipelines</p>
        </div>
        <div className="text-gray-400 font-bold text-xl shrink-0">→</div>
        <div className="flex-1 bg-[#E8F5EE] text-[#006837] rounded-xl p-4">
          <p className="text-xs font-semibold text-[#006837] uppercase tracking-wide mb-0.5">With AI</p>
          <p className="text-lg font-bold">2–3 days</p>
          <p className="text-xs text-[#006837]">Auto-generated scripts with validation, logging, and edge cases</p>
        </div>
      </div>

      {/* ETL Configuration */}
      <div className="bg-white rounded-xl border border-gray-200 p-5">
        <h2 className="text-sm font-semibold text-gray-800 mb-4">ETL Configuration</h2>
        <div className="grid grid-cols-3 gap-6">
          {/* Column 1: Source Systems */}
          <div>
            <p className="text-xs font-semibold text-gray-500 uppercase tracking-wide mb-3">Source Systems</p>
            <div className="space-y-2">
              {SOURCES.map(src => (
                <label key={src.id} className="flex items-center gap-2.5 cursor-pointer">
                  <input
                    type="checkbox"
                    checked={sources.has(src.id)}
                    onChange={() => toggleSource(src.id)}
                    className="h-4 w-4 accent-[#006837]"
                  />
                  <span className="text-lg">{src.emoji}</span>
                  <div>
                    <p className="text-sm text-gray-800">{src.label}</p>
                    <p className="text-xs text-gray-400">{src.sub}</p>
                  </div>
                </label>
              ))}
            </div>
          </div>

          {/* Column 2: Target Table */}
          <div>
            <p className="text-xs font-semibold text-gray-500 uppercase tracking-wide mb-3">Target Table</p>
            <div className="space-y-2">
              {TARGET_TABLES.map(tbl => (
                <label key={tbl.id} className="flex items-center gap-2.5 cursor-pointer">
                  <input
                    type="radio"
                    name="target"
                    value={tbl.id}
                    checked={target === tbl.id}
                    onChange={() => setTarget(tbl.id)}
                    className="h-4 w-4 accent-[#006837]"
                  />
                  <span className="text-lg">{tbl.emoji}</span>
                  <p className="text-sm text-gray-800 font-mono">{tbl.label}</p>
                </label>
              ))}
            </div>
          </div>

          {/* Column 3: Include */}
          <div>
            <p className="text-xs font-semibold text-gray-500 uppercase tracking-wide mb-3">Include</p>
            <div className="space-y-2">
              {INCLUDE_OPTIONS.map(opt => (
                <label key={opt.id} className="flex items-center gap-2.5 cursor-pointer">
                  <input
                    type="checkbox"
                    checked={includes.has(opt.id)}
                    onChange={() => toggleInclude(opt.id)}
                    className="h-4 w-4 accent-[#006837]"
                  />
                  <p className="text-sm text-gray-800">{opt.label}</p>
                </label>
              ))}
            </div>
          </div>
        </div>

        <button className="bg-[#006837] text-white px-4 py-2 rounded-lg text-sm font-semibold hover:bg-[#004D28] transition-colors mt-4 w-full flex items-center justify-center gap-2">
          <Code2 className="h-4 w-4" />
          Generate ETL Script
        </button>
      </div>

      {/* AI Prompt Preview */}
      <div className="bg-white rounded-xl border border-gray-200 p-5">
        <h2 className="text-sm font-semibold text-gray-800 mb-3">AI Prompt Preview</h2>
        <pre className="bg-gray-900 rounded-xl p-5 text-green-400 font-mono text-xs leading-relaxed whitespace-pre-wrap">{`Generate a Python ETL script to build the Gold layer dim_farm table.

Source Systems:
- PostgreSQL (Feed Management): farms, cows, feed_records
- MongoDB (Production Tracking): farms, animals, production_records

Target: gold.dim_farm
Requirements: Include validation checks, logging. No rollback.
Handle: fuzzy farm name matching, address normalisation,
        deduplication across sources.`}</pre>
      </div>

      {/* Generated Script */}
      <div className="bg-white rounded-xl border border-gray-200 p-5">
        <div className="flex items-center justify-between mb-1">
          <h2 className="text-sm font-semibold text-gray-800">Generated ETL Script</h2>
          <button className="flex items-center gap-1.5 text-xs text-gray-500 border border-gray-200 rounded-lg px-3 py-1.5 hover:bg-gray-50 transition-colors">
            <RefreshCw className="h-3.5 w-3.5" />
            Regenerate
          </button>
        </div>
        <p className="text-xs text-gray-400 mb-3">dim_farm · Gold Schema · PySpark</p>
        <pre className="bg-gray-900 rounded-xl p-5 text-green-400 font-mono text-xs leading-relaxed whitespace-pre-wrap overflow-x-auto">
          {ETL_SCRIPT}
        </pre>
      </div>
    </div>
  )
}
